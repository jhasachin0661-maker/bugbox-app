import { NextRequest, NextResponse } from 'next/server';
import { createClient } from '@/lib/supabase/server';
import { generateReproductionSteps } from '@/lib/redact';

export async function POST(
  _request: NextRequest,
  { params }: { params: Promise<{ id: string }> }
) {
  try {
    const supabase = await createClient();
    const { id } = await params;

    // Fetch bug box
    const { data: bugBox } = await supabase
      .from('bug_boxes')
      .select('*')
      .eq('id', id)
      .single();

    if (!bugBox) {
      return NextResponse.json({ error: 'Bug box not found' }, { status: 404 });
    }

    // Fetch session data
    const { data: sessions } = await supabase
      .from('sessions')
      .select('*')
      .eq('bug_box_id', id)
      .limit(1);

    const session = sessions?.[0] || null;

    // Fetch evidence
    const [
      { data: events },
      { data: networkEvents },
      { data: consoleEvents },
    ] = await Promise.all([
      session
        ? supabase.from('events').select('*').eq('session_id', session.id).order('timestamp')
        : Promise.resolve({ data: [] }),
      session
        ? supabase.from('network_events').select('*').eq('session_id', session.id).order('timestamp')
        : Promise.resolve({ data: [] }),
      session
        ? supabase.from('console_events').select('*').eq('session_id', session.id).order('timestamp')
        : Promise.resolve({ data: [] }),
    ]);

    // Generate reproduction steps
    const steps = generateReproductionSteps(
      (events || []).map((e) => ({
        type: e.type,
        target: e.target,
        metadata: e.metadata,
      }))
    );

    // Format environment info
    const envSection = session
      ? `**Environment:**
- OS: ${session.os || 'Unknown'}
- Browser: ${session.browser || 'Unknown'}
- Viewport: ${session.viewport || 'Unknown'}
- Timezone: ${session.timezone || 'Unknown'}`
      : '**Environment:** Not captured';

    // Format reproduction steps
    const stepsSection =
      steps.length > 0
        ? steps.map((s, i) => `${i + 1}. ${s}`).join('\n')
        : 'No steps captured';

    // Format network errors
    const errorNetworkEvents = (networkEvents || []).filter((n) => n.status >= 400);
    const networkSection =
      errorNetworkEvents.length > 0
        ? errorNetworkEvents
            .map(
              (n) =>
                `- \`${n.method} ${n.endpoint}\` → HTTP **${n.status}** (${n.duration}ms)`
            )
            .join('\n')
        : 'No network errors captured';

    // Format console errors
    const errorConsoleEvents = (consoleEvents || []).filter(
      (c) => c.level === 'error' || c.level === 'warn'
    );
    const consoleSection =
      errorConsoleEvents.length > 0
        ? errorConsoleEvents
            .map((c) => `- \`[${c.level.toUpperCase()}]\` ${c.message}`)
            .join('\n')
        : 'No console errors captured';

    // Build GitHub issue body
    const issueBody = `## Bug Report

${bugBox.description ? bugBox.description + '\n\n' : ''}
${envSection}

---

## Reproduction Steps

${stepsSection}

---

## Network Errors

${networkSection}

---

## Console Errors

${consoleSection}

---

## Evidence

- **Bug Box ID:** \`${bugBox.id}\`
- **Severity:** ${bugBox.severity}
- **Status:** ${bugBox.status}
- **Captured At:** ${new Date(bugBox.created_at).toLocaleString()}

---

*Generated by [BUG//BOX](https://bugbox.dev) — Don't explain the bug. Package it.*
`;

    const issueTitle = bugBox.title;

    const githubToken = process.env.GITHUB_TOKEN;
    const githubOwner = process.env.GITHUB_OWNER;
    const githubRepo = process.env.GITHUB_REPO;

    if (githubToken && githubOwner && githubRepo) {
      const githubResponse = await fetch(
        `https://api.github.com/repos/${encodeURIComponent(githubOwner)}/${encodeURIComponent(githubRepo)}/issues`,
        {
          method: 'POST',
          headers: {
            Accept: 'application/vnd.github+json',
            Authorization: `Bearer ${githubToken}`,
            'X-GitHub-Api-Version': '2022-11-28',
            'Content-Type': 'application/json',
          },
          body: JSON.stringify({ title: issueTitle, body: issueBody }),
        }
      );

      if (!githubResponse.ok) {
        const errorBody = await githubResponse.text();
        console.error('GitHub issue creation failed:', githubResponse.status, errorBody.slice(0, 300));
        return NextResponse.json(
          { error: 'GitHub issue creation failed. Check repository permissions.' },
          { status: 502 }
        );
      }

      const createdIssue = await githubResponse.json();
      return NextResponse.json({
        title: issueTitle,
        body: issueBody,
        github_url: createdIssue.html_url,
        created: true,
      });
    }

    return NextResponse.json({
      title: issueTitle,
      body: issueBody,
      created: false,
    });
  } catch (err) {
    console.error('Unexpected error in /api/bugs/[id]/github POST:', err);
    return NextResponse.json({ error: 'Internal server error' }, { status: 500 });
  }
}
